import { expect, test } from '@playwright/test';
import { readFile } from 'node:fs/promises';
import { approveImportedData, openWorkspaceActions } from './review-helpers';
test.skip(process.env.E2E_SERVER_WORKSPACE === 'true', 'Personal workspace backup only.');
test('encrypted backup rejects wrong passwords without replacing data, then restores original bytes', async ({ page }) => {
  test.setTimeout(90_000);
  const original = Buffer.from('\uFEFFID,Revenue,Region\r\n001,10,West\r\n002,20,East\r\n');
  const passphrase = 'fixture password 2026';
  await page.goto('/upload');
  await page.locator('input[type="file"]:not([webkitdirectory])').first().setInputFiles({ name: 'protected.csv', mimeType: 'text/csv', buffer: original });
  await page.getByRole('button', { name: /visualize dashboard/i }).click(); await approveImportedData(page);
  await openWorkspaceActions(page);
  await page.getByRole('button', { name: 'Encrypted backup', exact: true }).click();
  const create = page.getByRole('dialog', { name: 'Create encrypted backup' });
  await expect(create.getByLabel('Backup passphrase', { exact: true })).toBeFocused();
  await page.keyboard.press('Shift+Tab');
  await expect(create.getByRole('button', { name: 'Encrypt and download' })).toBeFocused();
  await page.keyboard.press('Tab');
  await expect(create.getByLabel('Backup passphrase', { exact: true })).toBeFocused();
  await page.keyboard.press('Escape');
  await expect(create).toBeHidden();
  await openWorkspaceActions(page);
  await expect(page.getByRole('button', { name: 'Encrypted backup', exact: true })).toBeFocused();
  await openWorkspaceActions(page);
  await page.getByRole('button', { name: 'Encrypted backup', exact: true }).click();
  await create.getByLabel('Backup passphrase', { exact: true }).fill(passphrase);
  await create.getByLabel('Confirm backup passphrase').fill(passphrase);
  const download = page.waitForEvent('download');
  await create.getByRole('button', { name: 'Encrypt and download' }).click();
  const file = await download; const ciphertext = await readFile(await file.path());
  expect(ciphertext.subarray(0, 13).toString()).toBe('ADBACKUPENC1\n');
  expect(ciphertext.includes(original)).toBe(false);
  const readIds = () => page.evaluate(() => new Promise((resolve, reject) => {
    const open = indexedDB.open('analytics-dashboard-local-data'); open.onerror = () => reject(open.error);
    open.onsuccess = () => { const db = open.result; const request = db.transaction('datasetMetadata').objectStore('datasetMetadata').getAllKeys();
      request.onsuccess = () => { resolve(request.result); db.close(); }; request.onerror = () => reject(request.error); };
  }));
  const before = await readIds();
  await openWorkspaceActions(page);
  await page.getByLabel('Choose workspace backup').setInputFiles(await file.path());
  let unlock = page.getByRole('dialog', { name: 'Unlock encrypted backup' });
  await unlock.getByLabel('Backup passphrase', { exact: true }).fill('incorrect fixture password');
  await unlock.getByRole('button', { name: 'Unlock and restore' }).click();
  await expect(page.getByText(/Nothing was restored/)).toBeVisible();
  expect(await readIds()).toEqual(before);
  await openWorkspaceActions(page);
  await page.getByLabel('Choose workspace backup').setInputFiles(await file.path());
  unlock = page.getByRole('dialog', { name: 'Unlock encrypted backup' });
  await unlock.getByLabel('Backup passphrase', { exact: true }).fill(passphrase);
  await unlock.getByRole('button', { name: 'Unlock and restore' }).click();
  await approveImportedData(page);
  await expect.poll(async () => (await readIds()).some((id) => !before.includes(id))).toBe(true);
  await openWorkspaceActions(page);
  await page.getByRole('button', { name: 'Data Health' }).click();
  const originalDownload = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Original File', exact: true }).click();
  expect(await readFile(await (await originalDownload).path())).toEqual(original);
});
