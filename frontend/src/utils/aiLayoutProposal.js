import { CHART_TYPE_VALUES } from './chartTypes';
import { getDatasetColumnGroups, validateGraphConfiguration } from './graphConfiguration';

const columnName = (column) => typeof column === 'string' ? column : column?.name;

/** Only schema/profile metadata leaves the browser, after the user opts in. */
export const buildAIDashboardProfile = (dataset, goal, purpose = '') => {
  const groups = getDatasetColumnGroups(dataset);
  const columns = (dataset.columns || []).map((column) => {
    const name = columnName(column);
    const override = dataset.columnOverrides?.[name];
    const inferredType = groups.date.includes(name) || column?.type === 'date' ? 'date'
      : groups.numeric.includes(name) || column?.type === 'number' ? 'number' : 'string';
    const type = ['number', 'date', 'string'].includes(override?.type) ? override.type : inferredType;
    const role = override?.role
      || (groups.identifiers?.includes(name) ? 'identifier' : groups.ignored?.includes(name) ? 'ignore' : groups.measures.includes(name) ? 'measure' : 'dimension');
    return { name, type, role };
  }).filter(({ name, role }) => name && name.length <= 120 && role !== 'ignore').slice(0, 80);
  if (!columns.length) throw new Error('This dataset has no shareable column profile.');
  return {
    goal: ['overview', 'trends', 'comparisons', 'distribution'].includes(goal) ? goal : 'overview',
    purpose: String(purpose || '').trim().slice(0, 200),
    rowCount: Number.isFinite(Number(dataset.rowCount || dataset.rawRows?.length))
      ? Math.max(1, Math.min(1_000_000, Number(dataset.rowCount || dataset.rawRows?.length))) : 1,
    columns,
  };
};

/** Convert an untrusted model proposal into cards the dashboard already validates. */
export const validateAIDashboardProposal = (proposal, dataset, goal = 'overview') => {
  if (!proposal || typeof proposal.title !== 'string' || !Array.isArray(proposal.cards)) throw new Error('The AI did not return a valid dashboard proposal.');
  const groups = getDatasetColumnGroups(dataset);
  const allowedFields = new Set(groups.all.filter((field) => !groups.ignored.includes(field) && !groups.identifiers.includes(field)));
  const cards = proposal.cards.slice(0, 5).flatMap((card, index) => {
    if (!CHART_TYPE_VALUES.includes(card?.chartType)) return [];
    if (card.xField && !allowedFields.has(card.xField)) return [];
    const rowCount = card.yField === '__count__';
    if (rowCount ? card.aggregation !== 'count' || !['bar', 'line', 'area', 'pie', 'kpi'].includes(card.chartType) : card.yField && !allowedFields.has(card.yField)) return [];
    const candidate = {
      i: `ai_${index + 1}`,
      title: String(card.title || 'Suggested analysis').trim().slice(0, 80) || 'Suggested analysis',
      chartType: card.chartType,
      preferredX: String(card.xField || ''),
      preferredY: String(card.yField || ''),
      aggregation: ['sum', 'average', 'count', 'auto'].includes(card.aggregation) ? card.aggregation : 'auto',
      topN: 12,
      x: (index % 2) * 6,
      y: Math.floor(index / 2) * 4,
      w: 6,
      h: card.chartType === 'kpi' ? 3 : 4,
    };
    return validateGraphConfiguration(candidate, groups).valid ? [candidate] : [];
  });
  if (!cards.length) throw new Error('The AI proposal did not contain a valid chart for this dataset.');
  const coverage = [...new Set(cards.flatMap(({ preferredX, preferredY }) => [preferredX, preferredY]).filter((field) => field && field !== '__count__'))];
  const variety = new Set(cards.map(({ chartType }) => chartType)).size;
  return {
    id: `${dataset.id}_ai_${Date.now()}`,
    name: String(proposal.title).trim().slice(0, 80),
    goal: ['overview', 'trends', 'comparisons', 'distribution'].includes(goal) ? goal : 'overview',
    description: `${String(proposal.summary || 'AI-suggested layout').trim().slice(0, 220)} Fields and chart configurations were validated locally; numerical results are not generated by the model.`,
    score: Math.min(95, Math.round((coverage.length / Math.max(1, groups.all.length) * 50) + (variety / cards.length * 30) + 15)),
    coverage,
    layout: cards,
    aiGenerated: true,
  };
};
